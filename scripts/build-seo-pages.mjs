/* ── Writers ───────────────────────────────────────────────────────────── */

async function writeIfChanged(path, content) {
  if (existsSync(path)) {
    const current = await readFile(path, "utf8");
    if (current === content) return false;
  }
  await writeFile(path, content, "utf8");
  return true;
}

function pageOutputPath(href) {
  // Flat "<slug>.html" rather than "<slug>/index.html".
  //
  // The directory form needs either a rewrite or an implicit directory-index
  // lookup, and both are fragile here: Vite's dev server answers any unknown
  // extensionless path with the SPA (so pages are unreachable locally), and on
  // Vercel a framework-level SPA fallback can shadow a rewrite. A flat file
  // plus "cleanUrls" is resolved by the host's normal filesystem step, before
  // any SPA fallback, so it behaves identically in dev, preview and production.
  return join(PUBLIC, href.replace(/^\//, "") + ".html");
}

/* ── Remove stale output ───────────────────────────────────────────────── */

/**
 * Delete generated page files that are no longer in the page list. Without
 * this, renaming a slug leaves the old page published and indexed, which is
 * worse than a 404 because it looks intentional.
 *
 * Only files carrying GENERATED_MARKER are candidates. An earlier version
 * deleted any unrecognised .html file and, in doing so, removed the Google
 * Search Console verification file — which would have silently unverified the
 * domain. Anything hand-authored in public/ is now untouchable by construction.
 */
async function pruneStale() {
  const wanted = new Set(
    [...PAGES, ...ARTICLES].map((p) => p.href.replace(/^\//, "") + ".html"),
  );

  const removed = [];

  const collect = async (dir) => {
    for (const entry of await readdir(dir, { withFileTypes: true })) {
      const p = join(dir, entry.name);
      if (entry.isDirectory()) {
        if (entry.name === "images") continue; // never touch asset directories
        await collect(p);
        continue;
      }
      if (!entry.name.endsWith(".html")) continue;

      const rel = p.slice(PUBLIC.length + 1).replace(/\\/g, "/");
      if (wanted.has(rel)) continue;

      // The ownership test. Everything else is hand-authored and stays.
      const contents = await readFile(p, "utf8").catch(() => "");
      if (!contents.includes(GENERATED_MARKER)) continue;

      const { rm } = await import("node:fs/promises");
      await rm(p, { force: true });
      removed.push(rel);
    }
  };

  await collect(PUBLIC);
  return removed;
}

/* ── Main ──────────────────────────────────────────────────────────────── */

const check = process.argv.includes("--check");

validate(ALL);

let written = 0;
let unchanged = 0;
const drift = [];

for (const page of [...PAGES, ...ARTICLES]) {
  const out = pageOutputPath(page.href);
  const html = renderPage(page, ALL);

  if (check) {
    if (!existsSync(out) || (await readFile(out, "utf8")) !== html) {
      drift.push(page.href);
    }
    continue;
  }

  await mkdir(dirname(out), { recursive: true });
  if (await writeIfChanged(out, html)) written++;
  else unchanged++;
}

// The blog lives one level deeper, so its directories need the same treatment.
if (!check) {
  const removed = await pruneStale();
  if (removed.length) console.log(`pruned stale page directories: ${removed.join(", ")}`);
}

const sitemap = renderSitemap(ALL);
const llms = renderLlmsTxt() + "\n";

if (check) {
  const sitemapPath = join(PUBLIC, "sitemap.xml");
  const llmsPath = join(PUBLIC, "llms.txt");
  const sitemapDrift = !existsSync(sitemapPath) || (await readFile(sitemapPath, "utf8")) !== sitemap;
  const llmsDrift = !existsSync(llmsPath) || (await readFile(llmsPath, "utf8")) !== llms;

  if (drift.length || sitemapDrift || llmsDrift) {
    console.error("SEO output is out of date. Run: npm run build:seo");
    for (const d of drift) console.error(`  page:  ${d}`);
    if (sitemapDrift) console.error("  sitemap.xml");
    if (llmsDrift) console.error("  llms.txt");
    process.exit(1);
  }

  console.log(`SEO output is current (${ALL.length - 1} generated pages).`);
} else {
  if (await writeIfChanged(join(PUBLIC, "sitemap.xml"), sitemap)) {
    console.log("wrote public/sitemap.xml");
  }
  if (await writeIfChanged(join(PUBLIC, "llms.txt"), llms)) {
    console.log("wrote public/llms.txt");
  }
  console.log(
    `${written} page(s) written, ${unchanged} unchanged. sitemap covers ${ALL.length} URLs.`,
  );
}