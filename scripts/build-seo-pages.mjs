#!/usr/bin/env node
/**
 * Generate the SEO landing pages and blog articles into public/.
 *
 * Why generated rather than hand-written: fifteen pages all have to agree.
 * The platform line, the telemetry answer, the risk tiers and the version
 * number are each stated many times across the site, and hand-maintaining that
 * is how a site ends up publishing three different claims about the same fact.
 * Every page reads them from ./facts.mjs instead, and this script fails loudly
 * if two pages disagree.
 *
 * Output layout is one directory per slug so each page has a clean URL with no
 * extension:
 *
 *   public/mac-storage-cleaner/index.html   ->  /mac-storage-cleaner
 *
 * Vite copies public/ into the build verbatim, so these ship as static files
 * with no JavaScript and no framework. vercel.json adds explicit rewrites so
 * the extensionless path resolves regardless of how the host handles directory
 * indexes.
 *
 * Usage:
 *   node scripts/build-seo-pages.mjs           # write pages + sitemap + llms.txt
 *   node scripts/build-seo-pages.mjs --check   # verify on-disk output is current
 */

import { writeFile, readFile, mkdir, readdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { PAGES } from "./seo/content-pages.mjs";
import { ARTICLES } from "./seo/content-articles.mjs";
import { renderPage, renderSitemap, SITE } from "./seo/render.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const PUBLIC = join(ROOT, "public");

/** Homepage is a React SPA and is not generated here. It appears in the sitemap only. */
const HOMEPAGE = {
  href: "/",
  title: `${SITE.name}: Free Open-Source Mac & Windows Storage Cleaner`,
  description:
    "Free, open-source Mac and Windows cleaner. Clear Xcode DerivedData, npm and Homebrew caches, remove app leftovers, monitor CPU/RAM. No telemetry in the app.",
  navTitle: "Home",
  footerTitle: "Home",
  crumb: "Home",
  priority: 1.0,
  inHeader: false,
  group: "home",
};

const ALL = [HOMEPAGE, ...PAGES, ...ARTICLES];

/**
 * Ownership stamp written into every generated page.
 *
 * Must stay byte-identical to the marker in scripts/seo/render.mjs. It is what
 * lets pruneStale tell generated pages from hand-authored ones.
 */
const GENERATED_MARKER = "Generated by scripts/build-seo-pages.mjs";

/* ── Validation ────────────────────────────────────────────────────────── */

/**
 * Cheap guards against the failure modes that actually happen when content is
 * generated: two pages fighting over one slug, a title long enough to be
 * truncated in SERPs, a description over the pixel limit, and a cross-link to a
 * page that does not exist.
 */
function validate(pages) {
  const errors = [];
  const seen = new Map();

  for (const p of pages) {
    const label = p.href || p.title;

    if (!p.href) errors.push(`${label}: no href`);
    if (seen.has(p.href)) errors.push(`${label}: duplicate href, also defined as ${seen.get(p.href)}`);
    seen.set(p.href, label);

    // The homepage is the React SPA and is hand-maintained in index.html, so it
    // carries no generator metadata and is exempt from these checks.
    if (p.href === "/") continue;

    if (!p.title) errors.push(`${label}: no title`);
    else if (p.title.length > 62) errors.push(`${label}: title is ${p.title.length} chars, will truncate in SERPs`);

    if (!p.description) errors.push(`${label}: no description`);
    else if (p.description.length > 165) errors.push(`${label}: description is ${p.description.length} chars`);

    if (!p.h1) errors.push(`${label}: no h1`);
    if (!p.lede) errors.push(`${label}: no lede / definition paragraph`);

    // Every page must carry at least one outbound link, or it is a dead end.
    const hasCta = (p.blocks || []).some((b) => b.t === "cta");
    const hasRelated = (p.blocks || []).some((b) => b.t === "related");
    if (!hasCta && !hasRelated) errors.push(`${label}: no CTA or related links`);

    for (const b of p.blocks || []) {
      if (b.t === "related") {
        for (const id of b.ids) {
          if (!pages.some((x) => x.href === id)) errors.push(`${label}: related link to unknown page ${id}`);
        }
      }
    }

    if (p.faqs && p.faqs.length) {
      for (const f of p.faqs) {
        if (!f.q || !f.a) errors.push(`${label}: FAQ entry missing question or answer`);
      }
    }
  }

  if (errors.length) {
    console.error("Content validation failed:\n" + errors.map((e) => "  - " + e).join("\n"));
    process.exit(1);
  }
}

