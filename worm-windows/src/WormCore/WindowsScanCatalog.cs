    /// <summary>
    /// The set of roots a rule is allowed to produce targets inside, derived from
    /// the rules themselves rather than hand-maintained.
    ///
    /// This is the cheapest available bound on the damage a wrong rule can do:
    /// even if discovery produces a surprising path, the safety policy refuses
    /// anything outside these roots. On macOS a hand-kept equivalent list
    /// silently drifted and refused 228 MB of a tool's own cache as "outside a
    /// cleanable folder", so this is derived instead.
    /// </summary>
    public static IEnumerable<string> CleanableRoots()
    {
        var roots = new SortedSet<string>(StringComparer.OrdinalIgnoreCase);

        foreach (var rule in GetRules())
        {
            var expanded = rule.PathExpression;

            switch (rule.Kind)
            {
                case RuleKind.Directory:
                case RuleKind.Children:
                case RuleKind.Files:
                    roots.Add(WindowsPaths.Expand(expanded));
                    break;

                case RuleKind.Glob:
                {
                    // Declare the literal parent of the wildcard, not the pattern.
                    var parent = Path.GetDirectoryName(expanded);
                    if (!string.IsNullOrEmpty(parent)) roots.Add(WindowsPaths.Expand(parent));
                    else roots.Add(WindowsPaths.Expand(expanded));
                    break;
                }
            }
        }

        return roots;
    }
}
