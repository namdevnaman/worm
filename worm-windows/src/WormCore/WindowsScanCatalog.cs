    public static IReadOnlyList<CleanRule> RulesFor(string category)
        => GetRules().Where(r => r.Category == category).ToList();

    // ------------------------------------------------------------------ expansion
    /// <summary>
    /// Expand a rule into concrete target paths. Missing paths are skipped, and
    /// every candidate still has to pass the safety policy before it is shown.
    /// </summary>
    public static IEnumerable<string> ExpandTargets(CleanRule rule)
    {
        IEnumerable<string> raw;

        switch (rule.Kind)
        {
            case RuleKind.Directory:
            case RuleKind.Files:
                raw = new[] { WindowsPaths.Expand(rule.PathExpression) };
                break;

            case RuleKind.Children:
                raw = ChildrenOf(WindowsPaths.Expand(rule.PathExpression), rule.KeepNames);
                break;

            case RuleKind.Glob:
                raw = ExpandGlob(rule);
                break;

            case RuleKind.CacheLeaves:
                raw = ExpandCacheLeaves(rule);
                break;

            default:
                raw = Array.Empty<string>();
                break;
        }

        if (rule.Kind == RuleKind.Files)
            raw = raw.Where(p => File.Exists(p) && MatchesExtension(p, rule.Extensions));

        return raw;
    }

    private static IEnumerable<string> ChildrenOf(string basePath, string[]? keepNames)
    {
        if (!Directory.Exists(basePath)) yield break;

        string[] entries;
        try { entries = Directory.GetFileSystemEntries(basePath); }
        catch { yield break; }

        foreach (var entry in entries)
        {
            var name = Path.GetFileName(entry);

            // Never descend into dot-directories.
            if (name.StartsWith('.')) continue;

            if (keepNames != null &&
                keepNames.Any(k => name.Equals(k, StringComparison.OrdinalIgnoreCase)))
            {
                continue;
            }

            yield return entry;
        }
    }

    private static IEnumerable<string> ExpandGlob(CleanRule rule)
    {
        var pattern = WindowsPaths.Expand(rule.PathExpression);
        var dir = Path.GetDirectoryName(pattern);
        var leaf = Path.GetFileName(pattern);

        if (string.IsNullOrEmpty(dir) || string.IsNullOrEmpty(leaf)) yield break;
        if (!Directory.Exists(dir)) yield break;

        if (rule.GlobDepth <= 0)
        {
            foreach (var match in SafeGetDirectories(dir, leaf)) yield return match;
            yield break;
        }

        string[] parents;
        try { parents = SafeGetDirectories(dir, leaf); }
        catch { yield break; }

        foreach (var parent in parents)
        {
            string[] children;
            try { children = Directory.GetDirectories(parent); }
            catch { continue; }
            foreach (var child in children)
            {
                var name = Path.GetFileName(child);
                if (rule.KeepNames != null &&
                    rule.KeepNames.Any(k => name.Equals(k, StringComparison.OrdinalIgnoreCase)))
                {
                    continue;
                }
                yield return child;
            }
        }
    }

    /// <summary>
    /// Two levels deep: every vendor folder under the base, then only its
    /// known cache leaves. A vendor folder itself is never returned.
    /// </summary>
    private static IEnumerable<string> ExpandCacheLeaves(CleanRule rule)
    {
        var baseDir = WindowsPaths.Expand(rule.PathExpression);
        if (!Directory.Exists(baseDir)) yield break;

        string[] vendors;
        try { vendors = Directory.GetDirectories(baseDir); }
        catch { yield break; }

        foreach (var vendor in vendors)
        {
            var vendorName = Path.GetFileName(vendor);
            if (string.IsNullOrWhiteSpace(vendorName)) continue;
            if (vendorName.StartsWith('.')) continue;
            if (NeverDescend.Any(n => n.Equals(vendorName, StringComparison.OrdinalIgnoreCase)))
                continue;

            string[] leaves;
            try { leaves = Directory.GetDirectories(vendor); }
            catch { continue; }

            foreach (var leaf in leaves)
            {
                var leafName = Path.GetFileName(leaf);
                if (!CacheLeafNames.Contains(leafName, StringComparer.OrdinalIgnoreCase)) continue;

                // A leaf that is a junction could point anywhere, so it is only
                // accepted when it resolves inside the vendor folder.
                var resolved = WindowsSafetyPolicy.ResolvePhysicalPath(leaf);
                if (!WindowsSafetyPolicy.IsUnder(resolved, vendor)) continue;

                yield return leaf;
            }
        }
    }

    private static string[] SafeGetDirectories(string dir, string pattern)
    {
        try { return Directory.GetDirectories(dir, pattern); }
        catch { return Array.Empty<string>(); }
    }

    private static bool MatchesExtension(string path, string[]? extensions)
    {
        if (extensions == null || extensions.Length == 0) return true;
        var ext = Path.GetExtension(path);
        // An empty entry in the list means "match everything".
        return extensions.Any(e => e.Length == 0 || e.Equals(ext, StringComparison.OrdinalIgnoreCase));
    }

    /// <summary>Age gate: 0 means always eligible.</summary>
    public static bool PassesAge(string path, int minAgeDays)
    {
        if (minAgeDays <= 0) return true;
        try
        {
            var info = new FileInfo(path);
            if (!info.Exists && !Directory.Exists(path)) return false;
            var stamp = Directory.Exists(path)
                ? Directory.GetLastWriteTime(path)
                : info.LastWriteTime;
            return DateTime.Now - stamp > TimeSpan.FromDays(minAgeDays);
        }
        catch
        {
            return false;
        }
    }

