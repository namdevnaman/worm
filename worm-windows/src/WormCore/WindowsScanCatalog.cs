using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;

namespace Worm.Core;

public enum RiskLevel
{
    Regenerable,  // Safe cache, temp files, build artifacts
    ReDownload,   // Package manager caches; needs a re-download
    UserData,     // Important data, explicit confirmation required
    Unsafe        // Refused by the safety policy
}

/// <summary>
/// How a rule expands into concrete targets. Windows previously had a single
/// implicit shape, which is why it could not express per-child targeting or
/// profile globs.
/// </summary>
public enum RuleKind
{
    /// <summary>The literal directory itself is one target.</summary>
    Directory,

    /// <summary>Every direct child of a base directory is its own target.</summary>
    Children,

    /// <summary>Every matching file (non-recursive) in a directory.</summary>
    Files,

    /// <summary>
    /// Match a pattern whose wildcard sits in the final component, then take
    /// the match itself (depth 0) or its child directories (depth >= 1).
    /// Only the last component may contain * or ?, by design: a recursive
    /// pattern would let a discovery bug reach anywhere.
    /// </summary>
    Glob,

    /// <summary>
    /// Walk one level into every vendor folder under a base directory and take
    /// only the children whose name is a known cache leaf.
    ///
    /// This exists because enumerating the children of %LOCALAPPDATA% or
    /// %APPDATA% wholesale is catastrophic: it targets Packages (every Store and
    /// UWP app's data) and every installed app's own folder. The macOS catalog
    /// does the same thing with its applicationSupportLeaves list, and this is
    /// that approach.
    /// </summary>
    CacheLeaves,
}

public record CleanRule(
    string Id,
    string Name,
    string Category,
    string Description,
    RiskLevel Risk,
    string PathExpression,
    RuleKind Kind = RuleKind.Directory,
    string[]? Extensions = null,
    string[]? KeepNames = null,
    int MinAgeDays = 0,
    int GlobDepth = 0,
    bool RequiresElevation = false
);

